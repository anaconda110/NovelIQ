"""数据库输入行的只读结构协议，不引用文本处理实现"""

from __future__ import annotations

from typing import Protocol


class LevelRecord(Protocol):
    @property
    def value(self) -> str: ...


class ChapterRecord(Protocol):
    @property
    def chapter_id(self) -> int: ...
    @property
    def sequence(self) -> int: ...
    @property
    def title(self) -> str: ...
    @property
    def display_title(self) -> str: ...
    @property
    def display_index_label(self) -> str | None: ...
    @property
    def level(self) -> LevelRecord: ...
    @property
    def start_char(self) -> int: ...
    @property
    def end_char(self) -> int: ...


class ChunkRecord(Protocol):
    @property
    def chapter_id(self) -> int: ...
    @property
    def text(self) -> str: ...
    @property
    def start(self) -> int: ...
    @property
    def end(self) -> int: ...


class ParagraphRecord(Protocol):
    @property
    def paragraph_id(self) -> int | None: ...
    @property
    def chapter_id(self) -> int | None: ...
    @property
    def paragraph_index(self) -> int: ...
    @property
    def source_paragraph_index(self) -> int: ...
    @property
    def fragment_index(self) -> int: ...
    @property
    def local_start_char(self) -> int: ...
    @property
    def local_end_char(self) -> int: ...
    @property
    def global_start_char(self) -> int | None: ...
    @property
    def global_end_char(self) -> int | None: ...
    @property
    def char_count(self) -> int: ...
    @property
    def token_count(self) -> int | None: ...
    @property
    def text(self) -> str: ...
